export function marketingT(locale:MarketingLocale) {
  return (english:string):string => translateMarketing(locale,english);
}
export function translateMarketing(locale:MarketingLocale, english:string):string {
  if(locale!=='tr')return english;
  if(turkish[english])return turkish[english];
  const count=english.match(/^(\d+) (process|processes|workspace|workspaces)$/);
  if(count)return count[1]+' '+(count[2].startsWith('process')?'süreç':'çalışma alanı');
  const max=english.match(/^Up to (\d+) workspaces$/);
  if(max)return 'En fazla '+max[1]+' çalışma alanı';
  const daily=english.match(/^Up to (\d+) requests\/day per user$/);
  if(daily)return 'Kullanıcı başına günde en fazla '+daily[1]+' talep';
  return english;
}
export function hasTurkishMarketingCopy(english:string):boolean {
  return Object.prototype.hasOwnProperty.call(turkish,english);
}
