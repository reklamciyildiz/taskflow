const text=(name:string)=>readFileSync(name,'utf8');
const templateIds=new Set(PROCESS_TEMPLATES.map(t=>t.id));
assert.equal(templateIds.size,PROCESS_TEMPLATES.length);
assert.ok(PROCESS_TEMPLATES.length>=8);
for(const t of PROCESS_TEMPLATES){
  assert.ok(t.title&&t.description&&t.outcome);
  assert.equal(t.stages.filter(s=>s.isTerminal===true).length,1,`${t.id} must have one terminal`);
  const a=instantiateProcessTemplate(t.id);
  const b=instantiateProcessTemplate(t.id);
  assert.doesNotThrow(()=>validateStageConfig(a));
  assert.deepEqual(a.map(s=>s.title),t.stages.map(s=>s.title));
  assert.equal(a.filter(s=>s.isTerminal).length,1);
  assert.equal(new Set(a.map(s=>s.id)).size,a.length);
  assert.ok(a.every(s=>!b.some(other=>other.id===s.id)),`${t.id} shares IDs`);
}
assert.equal(getProcessTemplate('does-not-exist'),undefined);
assert.throws(()=>instantiateProcessTemplate('bad-id' as ProcessTemplateId));

const project={id:'proc',teamId:'team',columnConfig:instantiateProcessTemplate('simple')} as Project;
const [first,second,terminal]=project.columnConfig;
const base={id:'task',projectId:'proc',teamId:'team',status:first.id} as Task;
const empty=calculateFirstSuccessProgress({projects:[],tasks:[],teamId:'team'});
assert.equal(empty.count,0);
const one=calculateFirstSuccessProgress({projects:[project],tasks:[],teamId:'team'});
assert.equal(one.count,1);
const two=calculateFirstSuccessProgress({projects:[project],tasks:[base],teamId:'team'});
assert.equal(two.count,2);
const three=calculateFirstSuccessProgress({projects:[project],tasks:[{...base,status:terminal.id}],teamId:'team'});
assert.equal(three.count,3);
assert.equal(three.complete,true);
assert.equal(calculateFirstSuccessProgress({projects:[project],tasks:[{...base,status:second.id}],teamId:'team'}).count,2);
assert.equal(calculateFirstSuccessProgress({projects:[project],tasks:[{...base,status:'done'}],teamId:'team'}).count,2);
assert.equal(calculateFirstSuccessProgress({projects:[project],tasks:[{...base,status:terminal.id,teamId:'other'}],teamId:'team'}).count,1);
assert.equal(calculateFirstSuccessProgress({projects:[project],tasks:[{...base,status:terminal.id}],teamId:'other'}).count,0);
assert.equal(calculateFirstSuccessProgress({projects:[project],tasks:[{...base,projectId:null,status:terminal.id}],teamId:'team'}).count,1);
assert.equal(calculateFirstSuccessProgress({projects:[project],tasks:[{...base,status:terminal.id}],teamId:null}).count,0);
assert.equal(project.columnConfig.filter(c=>c.isTerminal).length,1);

